-- Petualangan Kata: lean HUD, 3D movement and physical category interactions.
local RS=game:GetService("ReplicatedStorage")
local UI=require(script.Parent:WaitForChild("BCUI"))
local bridge=RS:WaitForChild("BCForestBridge"):WaitForChild("Event")
local ui=UI.new("PETUALANGAN KATA","Temukan kata di hutan bahasa")
ui:compact(true)
ui:backToLobby(bridge)
local function welcome()
 ui:clear()
 ui:setStats("HUTAN KATA • 12 TANTANGAN")
 ui:label("Bukan kuis tombol: berlarilah menuju salah satu dari tiga zona kategori di hutan.",19)
 ui:label("Cari KATA BENDA, KATA KERJA, atau KATA SIFAT. Dekati papan lalu tekan E atau tombol interaksi di ponsel.",15)
 ui:button("Mulai Jelajah",function()
  ui:clear();ui:setStats("Mempersiapkan kata...")
  bridge:FireServer("start")
 end,"Leaf")
end
bridge.OnClientEvent:Connect(function(kind,data)
 if kind=="round" and type(data)=="table" then
  ui:clear()
  ui:setStats(string.format("KATA %d/%d  •  %d POIN",data.round,data.total,data.score))
  ui:label("Temukan kategori untuk:",18)
  ui:label(tostring(data.word),27)
  ui:label("Bergeraklah ke salah satu gerbang kategori, lalu tekan tombol interaksi.",15)
 elseif kind=="feedback" and type(data)=="table" then
  ui:clear()
  ui:setStats("SKOR: "..tostring(data.score))
  ui:label(data.correct and "Hebat, kategorimu tepat!" or "Belum tepat, ayo coba lagi.",21)
  ui:label("Kategori benar: "..tostring(data.answer),18)
  ui:button("Lanjut ke Kata Berikutnya",function()
   ui:clear();ui:setStats("Memuat tantangan...")
   bridge:FireServer("next")
  end,"Leaf")
 elseif kind=="finished" and type(data)=="table" then
  ui:clear()
  ui:setStats("JELAJAH SELESAI")
  ui:label("Skor: "..tostring(data.score).."/"..tostring(data.total),23)
  ui:button("Jelajah Lagi",welcome,"Leaf")
 elseif kind=="message" then
  ui:say(tostring(data))
 end
end)
welcome()
